CREATE OR REPLACE FUNCTION hutube.validate_recommendation_agent_user()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM hutube.users u
        WHERE u.user_id = NEW.user_id
          AND u.is_synthetic = TRUE
    ) THEN
        RAISE EXCEPTION 'recommendation_agent_profiles.user_id must reference a synthetic user';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_recommendation_agent_user
    ON recommendation_agent_profiles;

CREATE TRIGGER trg_recommendation_agent_user
BEFORE INSERT OR UPDATE OF user_id
ON recommendation_agent_profiles
FOR EACH ROW
EXECUTE FUNCTION hutube.validate_recommendation_agent_user();

