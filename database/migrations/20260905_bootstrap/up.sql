/*=============================================================================
  HuTube - PostgreSQL Database Schema
  Target: PostgreSQL 16+ (works well with Neon / Supabase / managed PostgreSQL)

  Purpose
  -------
  - Rebuild the previous SQL Server schema as PostgreSQL.
  - Expand the database to cover the finalized HuTube business flows:
      * Web User + Mobile User
      * Web Admin / RBAC
      * Channel ownership & member permissions
      * Video upload / processing / moderation / publishing
      * Player / history / interactions / comments / playlists
      * Search / subscriptions / notifications
      * Report / Policy / Strike / Appeal / Copyright
      * Plan / Subscription / Payment / Refund
      * Recommendation MBMF metadata / model versioning
      * Analytics aggregates
      * HuAI action confirmation
      * Audit / system configuration

  Notes
  -----
  1. This is a BOOTSTRAP schema, not a replacement for application migrations.
     After the initial database is created, use EF Core migrations for changes.
  2. IDs use UUID generated by pgcrypto.gen_random_uuid().
  3. Timestamps use TIMESTAMPTZ and should be written in UTC.
  4. Important business entities use soft-delete/status instead of cascade-delete.
  5. Web/Mobile/Admin share the same backend business data.
=============================================================================*/

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE SCHEMA IF NOT EXISTS hutube;
SET search_path TO hutube, public;

/*=============================================================================
  0. Common helper
=============================================================================*/

CREATE OR REPLACE FUNCTION hutube.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

/*=============================================================================
  1. Identity, authentication and personal settings
=============================================================================*/

CREATE TABLE IF NOT EXISTS users (
    user_id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username                CITEXT NOT NULL,
    email                   CITEXT NOT NULL,
    display_name            VARCHAR(120) NOT NULL,
    avatar_url              TEXT,
    status                  VARCHAR(20) NOT NULL DEFAULT 'pending',
    email_verified_at       TIMESTAMPTZ,
    last_login_at           TIMESTAMPTZ,
    failed_login_attempts   INTEGER NOT NULL DEFAULT 0,
    locked_until            TIMESTAMPTZ,
    is_synthetic            BOOLEAN NOT NULL DEFAULT FALSE,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at              TIMESTAMPTZ,
    delete_reason           TEXT,
    CONSTRAINT ck_users_username
        CHECK (char_length(btrim(username::text)) BETWEEN 3 AND 50),
    CONSTRAINT ck_users_display_name
        CHECK (char_length(btrim(display_name)) BETWEEN 1 AND 120),
    CONSTRAINT ck_users_failed_login
        CHECK (failed_login_attempts >= 0),
    CONSTRAINT ck_users_status
        CHECK (status IN ('pending','active','suspended','banned','deleted'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_users_username_active
    ON users (username) WHERE deleted_at IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email_active
    ON users (email) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS auth_identities (
    auth_identity_id        UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                 UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    provider                VARCHAR(30) NOT NULL,
    provider_subject        VARCHAR(255),
    password_hash           VARCHAR(255),
    provider_email          CITEXT,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_auth_identities_provider
        CHECK (provider IN ('local','google','facebook')),
    CONSTRAINT ck_auth_identities_local
        CHECK (
            (provider = 'local' AND password_hash IS NOT NULL)
            OR provider <> 'local'
        )
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_auth_identities_provider_subject
    ON auth_identities(provider, provider_subject)
    WHERE provider_subject IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ux_auth_identities_local_user
    ON auth_identities(user_id)
    WHERE provider = 'local';

CREATE TABLE IF NOT EXISTS user_sessions (
    session_id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                 UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    refresh_token_hash      VARCHAR(255) NOT NULL,
    jti                     UUID NOT NULL DEFAULT gen_random_uuid(),
    device_name             VARCHAR(200),
    platform                VARCHAR(30),
    app_version             VARCHAR(50),
    ip_address              INET,
    user_agent              TEXT,
    issued_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at              TIMESTAMPTZ NOT NULL,
    last_active_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at              TIMESTAMPTZ,
    revoke_reason           TEXT,
    replaced_by_session_id  UUID REFERENCES user_sessions(session_id) ON DELETE SET NULL,
    CONSTRAINT uq_user_sessions_jti UNIQUE (jti),
    CONSTRAINT uq_user_sessions_refresh_hash UNIQUE (refresh_token_hash),
    CONSTRAINT ck_user_sessions_expiry CHECK (expires_at > issued_at)
);

CREATE INDEX IF NOT EXISTS ix_user_sessions_active
    ON user_sessions(user_id, expires_at DESC)
    WHERE revoked_at IS NULL;

CREATE TABLE IF NOT EXISTS email_verification_tokens (
    email_verification_token_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                 UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token_hash              VARCHAR(255) NOT NULL UNIQUE,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at              TIMESTAMPTZ NOT NULL,
    used_at                 TIMESTAMPTZ,
    CONSTRAINT ck_email_verify_expiry CHECK (expires_at > created_at)
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    password_reset_token_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                 UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token_hash              VARCHAR(255) NOT NULL UNIQUE,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at              TIMESTAMPTZ NOT NULL,
    used_at                 TIMESTAMPTZ,
    CONSTRAINT ck_password_reset_expiry CHECK (expires_at > created_at)
);

CREATE TABLE IF NOT EXISTS user_preferences (
    user_id                 UUID PRIMARY KEY REFERENCES users(user_id) ON DELETE CASCADE,
    language_code           VARCHAR(10) NOT NULL DEFAULT 'vi',
    theme                   VARCHAR(20) NOT NULL DEFAULT 'system',
    watch_history_enabled   BOOLEAN NOT NULL DEFAULT TRUE,
    search_history_enabled  BOOLEAN NOT NULL DEFAULT TRUE,
    personalization_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    mention_enabled         BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_user_preferences_theme CHECK (theme IN ('system','light','dark'))
);

CREATE TABLE IF NOT EXISTS user_blocks (
    blocker_user_id         UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    blocked_user_id         UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    reason                  TEXT,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (blocker_user_id, blocked_user_id),
    CONSTRAINT ck_user_blocks_self CHECK (blocker_user_id <> blocked_user_id)
);

CREATE TABLE IF NOT EXISTS search_histories (
    search_history_id       UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                 UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    keyword                 VARCHAR(500) NOT NULL,
    search_type             VARCHAR(30) NOT NULL DEFAULT 'all',
    searched_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_search_history_keyword CHECK (char_length(btrim(keyword)) > 0),
    CONSTRAINT ck_search_history_type
        CHECK (search_type IN ('all','video','channel','playlist','user','tag'))
);

CREATE INDEX IF NOT EXISTS ix_search_histories_user_time
    ON search_histories(user_id, searched_at DESC);

/*=============================================================================
  2. Admin access and RBAC
=============================================================================*/

CREATE TABLE IF NOT EXISTS admin_accounts (
    admin_account_id        UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                 UUID NOT NULL UNIQUE REFERENCES users(user_id),
    status                  VARCHAR(20) NOT NULL DEFAULT 'active',
    granted_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    disabled_at             TIMESTAMPTZ,
    last_admin_login_at     TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_admin_accounts_status CHECK (status IN ('active','disabled'))
);

CREATE TABLE IF NOT EXISTS roles (
    role_id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code                    CITEXT NOT NULL,
    name                    VARCHAR(100) NOT NULL,
    description             TEXT,
    is_system_role          BOOLEAN NOT NULL DEFAULT FALSE,
    status                  VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at              TIMESTAMPTZ,
    CONSTRAINT uq_roles_code UNIQUE (code),
    CONSTRAINT ck_roles_status CHECK (status IN ('active','inactive','deleted'))
);

CREATE TABLE IF NOT EXISTS permissions (
    permission_id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code                    CITEXT NOT NULL,
    name                    VARCHAR(150) NOT NULL,
    description             TEXT,
    status                  VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_permissions_code UNIQUE (code),
    CONSTRAINT ck_permissions_status CHECK (status IN ('active','inactive'))
);

CREATE TABLE IF NOT EXISTS role_permissions (
    role_id                 UUID NOT NULL REFERENCES roles(role_id) ON DELETE CASCADE,
    permission_id           UUID NOT NULL REFERENCES permissions(permission_id) ON DELETE CASCADE,
    assigned_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS admin_account_roles (
    admin_account_id        UUID NOT NULL REFERENCES admin_accounts(admin_account_id) ON DELETE CASCADE,
    role_id                 UUID NOT NULL REFERENCES roles(role_id) ON DELETE CASCADE,
    assigned_by_admin_id    UUID REFERENCES admin_accounts(admin_account_id) ON DELETE SET NULL,
    assigned_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (admin_account_id, role_id)
);

CREATE TABLE IF NOT EXISTS admin_permission_overrides (
    admin_account_id        UUID NOT NULL REFERENCES admin_accounts(admin_account_id) ON DELETE CASCADE,
    permission_id           UUID NOT NULL REFERENCES permissions(permission_id) ON DELETE CASCADE,
    effect                  VARCHAR(10) NOT NULL,
    expires_at              TIMESTAMPTZ,
    reason                  TEXT,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (admin_account_id, permission_id),
    CONSTRAINT ck_admin_permission_override_effect CHECK (effect IN ('allow','deny'))
);

/*=============================================================================
  3. Plans, paid subscription and payment
=============================================================================*/

CREATE TABLE IF NOT EXISTS plans (
    plan_id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code                    CITEXT NOT NULL UNIQUE,
    name                    VARCHAR(100) NOT NULL,
    description             TEXT,
    price                   NUMERIC(15,2) NOT NULL DEFAULT 0,
    currency                CHAR(3) NOT NULL DEFAULT 'VND',
    billing_cycle           VARCHAR(20) NOT NULL DEFAULT 'monthly',
    duration_days           INTEGER,
    storage_limit_bytes     BIGINT NOT NULL DEFAULT 0,
    max_upload_size_bytes   BIGINT NOT NULL DEFAULT 0,
    max_video_duration_sec  INTEGER,
    max_video_quality       VARCHAR(20),
    features                JSONB NOT NULL DEFAULT '{}'::jsonb,
    display_order           INTEGER NOT NULL DEFAULT 0,
    status                  VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at              TIMESTAMPTZ,
    CONSTRAINT ck_plans_price CHECK (price >= 0),
    CONSTRAINT ck_plans_storage CHECK (storage_limit_bytes >= 0),
    CONSTRAINT ck_plans_upload CHECK (max_upload_size_bytes >= 0),
    CONSTRAINT ck_plans_billing_cycle
        CHECK (billing_cycle IN ('free','monthly','quarterly','yearly','custom')),
    CONSTRAINT ck_plans_status CHECK (status IN ('active','inactive','archived','deleted'))
);

CREATE TABLE IF NOT EXISTS plan_subscriptions (
    plan_subscription_id    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                 UUID NOT NULL REFERENCES users(user_id),
    plan_id                 UUID NOT NULL REFERENCES plans(plan_id),
    status                  VARCHAR(20) NOT NULL DEFAULT 'pending',
    starts_at               TIMESTAMPTZ,
    ends_at                 TIMESTAMPTZ,
    auto_renew              BOOLEAN NOT NULL DEFAULT FALSE,
    cancelled_at            TIMESTAMPTZ,
    cancel_reason           TEXT,
    previous_subscription_id UUID REFERENCES plan_subscriptions(plan_subscription_id) ON DELETE SET NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_plan_subscriptions_status
        CHECK (status IN ('pending','active','expired','cancelled','past_due')),
    CONSTRAINT ck_plan_subscriptions_dates
        CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at > starts_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_plan_subscriptions_one_active_user
    ON plan_subscriptions(user_id)
    WHERE status IN ('pending','active','past_due');

CREATE TABLE IF NOT EXISTS plan_subscription_events (
    plan_subscription_event_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    plan_subscription_id    UUID NOT NULL REFERENCES plan_subscriptions(plan_subscription_id) ON DELETE CASCADE,
    event_type              VARCHAR(30) NOT NULL,
    old_plan_id             UUID REFERENCES plans(plan_id),
    new_plan_id             UUID REFERENCES plans(plan_id),
    metadata                JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_plan_subscription_event_type
        CHECK (event_type IN ('created','activated','renewed','upgraded','downgraded','cancelled','expired','past_due','restored'))
);

CREATE TABLE IF NOT EXISTS payment_transactions (
    payment_id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                 UUID NOT NULL REFERENCES users(user_id),
    plan_id                 UUID REFERENCES plans(plan_id),
    plan_subscription_id    UUID REFERENCES plan_subscriptions(plan_subscription_id) ON DELETE SET NULL,
    idempotency_key         VARCHAR(120) NOT NULL UNIQUE,
    gateway                 VARCHAR(30) NOT NULL,
    gateway_transaction_id  VARCHAR(200),
    amount                  NUMERIC(15,2) NOT NULL,
    currency                CHAR(3) NOT NULL DEFAULT 'VND',
    status                  VARCHAR(20) NOT NULL DEFAULT 'pending',
    failure_code            VARCHAR(100),
    failure_message         TEXT,
    paid_at                 TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_payment_amount CHECK (amount >= 0),
    CONSTRAINT ck_payment_gateway CHECK (gateway IN ('momo','zalopay','vnpay','bank_transfer','card','other')),
    CONSTRAINT ck_payment_status CHECK (status IN ('pending','processing','success','failed','cancelled','refunded'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_payment_gateway_transaction
    ON payment_transactions(gateway, gateway_transaction_id)
    WHERE gateway_transaction_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS ix_payment_user_time
    ON payment_transactions(user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS payment_refunds (
    refund_id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    payment_id              UUID NOT NULL REFERENCES payment_transactions(payment_id),
    requested_by_admin_id   UUID REFERENCES admin_accounts(admin_account_id) ON DELETE SET NULL,
    amount                  NUMERIC(15,2) NOT NULL,
    reason                  TEXT NOT NULL,
    gateway_refund_id       VARCHAR(200),
    status                  VARCHAR(20) NOT NULL DEFAULT 'pending',
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at            TIMESTAMPTZ,
    CONSTRAINT ck_refund_amount CHECK (amount > 0),
    CONSTRAINT ck_refund_status CHECK (status IN ('pending','processing','success','failed','cancelled'))
);

CREATE TABLE IF NOT EXISTS payment_webhook_events (
    payment_webhook_event_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    gateway                  VARCHAR(30) NOT NULL,
    external_event_id        VARCHAR(200),
    payment_id               UUID REFERENCES payment_transactions(payment_id) ON DELETE SET NULL,
    payload                  JSONB NOT NULL,
    signature_valid          BOOLEAN,
    processing_status       VARCHAR(20) NOT NULL DEFAULT 'pending',
    received_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at             TIMESTAMPTZ,
    error_message            TEXT,
    CONSTRAINT ck_webhook_processing_status CHECK (processing_status IN ('pending','processed','ignored','failed'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_webhook_gateway_event
    ON payment_webhook_events(gateway, external_event_id)
    WHERE external_event_id IS NOT NULL;

/*=============================================================================
  4. Channels, membership, channel permission and channel subscription
=============================================================================*/

CREATE TABLE IF NOT EXISTS channels (
    channel_id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_user_id           UUID NOT NULL REFERENCES users(user_id),
    name                    VARCHAR(120) NOT NULL,
    handle                  CITEXT NOT NULL,
    description             TEXT,
    avatar_url              TEXT,
    banner_url              TEXT,
    contact_email           CITEXT,
    watermark_url           TEXT,
    watermark_start_sec     INTEGER,
    status                  VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at              TIMESTAMPTZ,
    delete_reason           TEXT,
    CONSTRAINT ck_channels_name CHECK (char_length(btrim(name)) > 0),
    CONSTRAINT ck_channels_handle CHECK (char_length(btrim(handle::text)) BETWEEN 3 AND 50),
    CONSTRAINT ck_channels_watermark_time CHECK (watermark_start_sec IS NULL OR watermark_start_sec >= 0),
    CONSTRAINT ck_channels_status CHECK (status IN ('active','suspended','banned','deleted'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_channels_handle_active
    ON channels(handle) WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS ix_channels_owner
    ON channels(owner_user_id);

CREATE TABLE IF NOT EXISTS channel_quotas (
    channel_id              UUID PRIMARY KEY REFERENCES channels(channel_id),
    storage_limit_bytes     BIGINT NOT NULL DEFAULT 0,
    storage_used_bytes      BIGINT NOT NULL DEFAULT 0,
    video_count_limit       INTEGER,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_channel_quota_storage
        CHECK (storage_limit_bytes >= 0 AND storage_used_bytes >= 0 AND storage_used_bytes <= storage_limit_bytes),
    CONSTRAINT ck_channel_quota_video_limit
        CHECK (video_count_limit IS NULL OR video_count_limit >= 0)
);

CREATE TABLE IF NOT EXISTS channel_links (
    channel_link_id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    channel_id              UUID NOT NULL REFERENCES channels(channel_id) ON DELETE CASCADE,
    title                   VARCHAR(100) NOT NULL,
    url                     TEXT NOT NULL,
    position                INTEGER NOT NULL DEFAULT 1,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_channel_links_position UNIQUE(channel_id, position),
    CONSTRAINT ck_channel_links_position CHECK (position > 0)
);

CREATE TABLE IF NOT EXISTS channel_settings (
    channel_id              UUID PRIMARY KEY REFERENCES channels(channel_id) ON DELETE CASCADE,
    allow_comments          BOOLEAN NOT NULL DEFAULT TRUE,
    comment_moderation_mode VARCHAR(30) NOT NULL DEFAULT 'allow_all',
    link_policy             VARCHAR(20) NOT NULL DEFAULT 'allow',
    default_visibility      VARCHAR(20) NOT NULL DEFAULT 'private',
    default_category_id     UUID,
    default_language_code   VARCHAR(10),
    advanced_settings       JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_channel_comment_mode
        CHECK (comment_moderation_mode IN ('allow_all','hold_inappropriate','hold_all','disabled')),
    CONSTRAINT ck_channel_link_policy
        CHECK (link_policy IN ('allow','hold','block')),
    CONSTRAINT ck_channel_default_visibility
        CHECK (default_visibility IN ('public','unlisted','private'))
);

CREATE TABLE IF NOT EXISTS channel_permissions (
    channel_permission_id   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code                    CITEXT NOT NULL UNIQUE,
    name                    VARCHAR(150) NOT NULL,
    description             TEXT,
    status                  VARCHAR(20) NOT NULL DEFAULT 'active',
    CONSTRAINT ck_channel_permissions_status CHECK (status IN ('active','inactive'))
);

CREATE TABLE IF NOT EXISTS channel_roles (
    channel_role_id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code                    CITEXT NOT NULL UNIQUE,
    name                    VARCHAR(100) NOT NULL,
    description             TEXT,
    is_system_role          BOOLEAN NOT NULL DEFAULT TRUE,
    hierarchy_level         INTEGER NOT NULL DEFAULT 0,
    status                  VARCHAR(20) NOT NULL DEFAULT 'active',
    CONSTRAINT ck_channel_roles_status CHECK (status IN ('active','inactive'))
);

CREATE TABLE IF NOT EXISTS channel_role_permissions (
    channel_role_id         UUID NOT NULL REFERENCES channel_roles(channel_role_id) ON DELETE CASCADE,
    channel_permission_id   UUID NOT NULL REFERENCES channel_permissions(channel_permission_id) ON DELETE CASCADE,
    PRIMARY KEY (channel_role_id, channel_permission_id)
);

CREATE TABLE IF NOT EXISTS channel_members (
    channel_member_id       UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    channel_id              UUID NOT NULL REFERENCES channels(channel_id) ON DELETE CASCADE,
    user_id                 UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    channel_role_id         UUID NOT NULL REFERENCES channel_roles(channel_role_id),
    status                  VARCHAR(20) NOT NULL DEFAULT 'active',
    joined_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_channel_members UNIQUE(channel_id, user_id),
    CONSTRAINT ck_channel_members_status CHECK (status IN ('active','suspended','removed'))
);

CREATE TABLE IF NOT EXISTS channel_invitations (
    channel_invitation_id   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    channel_id              UUID NOT NULL REFERENCES channels(channel_id) ON DELETE CASCADE,
    invited_user_id         UUID REFERENCES users(user_id) ON DELETE CASCADE,
    invited_email           CITEXT,
    channel_role_id         UUID NOT NULL REFERENCES channel_roles(channel_role_id),
    invited_by_user_id      UUID NOT NULL REFERENCES users(user_id),
    status                  VARCHAR(20) NOT NULL DEFAULT 'pending',
    token_hash              VARCHAR(255) UNIQUE,
    expires_at              TIMESTAMPTZ NOT NULL,
    responded_at            TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_channel_invitation_target
        CHECK (num_nonnulls(invited_user_id, invited_email) >= 1),
    CONSTRAINT ck_channel_invitation_status
        CHECK (status IN ('pending','accepted','declined','expired','revoked')),
    CONSTRAINT ck_channel_invitation_expiry CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS ix_channel_invitations_pending
    ON channel_invitations(channel_id, expires_at)
    WHERE status = 'pending';

CREATE TABLE IF NOT EXISTS channel_subscriptions (
    channel_subscription_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                 UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    channel_id              UUID NOT NULL REFERENCES channels(channel_id) ON DELETE CASCADE,
    notification_level      VARCHAR(20) NOT NULL DEFAULT 'personalized',
    status                  VARCHAR(20) NOT NULL DEFAULT 'active',
    subscribed_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_channel_subscriptions UNIQUE(user_id, channel_id),
    CONSTRAINT ck_channel_subscription_level
        CHECK (notification_level IN ('all','personalized','off')),
    CONSTRAINT ck_channel_subscription_status CHECK (status IN ('active','paused'))
);

CREATE TABLE IF NOT EXISTS channel_blocked_words (
    channel_blocked_word_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    channel_id              UUID NOT NULL REFERENCES channels(channel_id) ON DELETE CASCADE,
    word                    CITEXT NOT NULL,
    status                  VARCHAR(20) NOT NULL DEFAULT 'active',
    created_by_user_id      UUID REFERENCES users(user_id) ON DELETE SET NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_channel_blocked_words UNIQUE(channel_id, word),
    CONSTRAINT ck_channel_blocked_words_status CHECK (status IN ('active','inactive'))
