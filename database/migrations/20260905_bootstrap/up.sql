        'comments',
        'notification_preferences',
        'notification_templates',
        'policies',
        'violation_types',
        'moderation_cases',
        'report_cases',
        'reports',
        'appeals',
        'copyright_requests',
        'huai_conversations',
        'system_settings',
        'feature_flags',
        'admin_resource_notes'
    ]
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%I_updated_at ON hutube.%I', table_name, table_name);
        EXECUTE format(
            'CREATE TRIGGER trg_%I_updated_at BEFORE UPDATE ON hutube.%I
             FOR EACH ROW EXECUTE FUNCTION hutube.set_updated_at()',
            table_name, table_name
        );
    END LOOP;
END $$;

